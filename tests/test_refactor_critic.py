import json

import pytest

from agent.agents.refactor import generate_patch
from agent.agents.critic import review_patch
from agent.models.contracts import LLMRequest, LLMResponse
from agent.models.provider import LLMProvider
from shared.schemas.finding import Finding, Severity
from shared.schemas.interfaces import Patch


class FakeProvider(LLMProvider):
    """Simulate structured model responses without calling Ollama."""

    def __init__(self):
        self.call_count = 0

    def generate(self, request: LLMRequest) -> LLMResponse:
        self.call_count += 1

        schema = request.response_format or {}
        properties = schema.get("properties", {})

        if "approved" in properties:
            response = {
                "approved": True,
                "confidence": 0.95,
                "issues": [],
                "explanation": (
                    "The patch uses parameterized SQL and "
                    "addresses the identified vulnerability."
                ),
                "recommended_changes": "None.",
            }

        elif "revised_source" in properties:
            response = {
                "revised_source": (
                    'user_id = input("User ID: ")\n'
                    'query = "SELECT * FROM users WHERE id = ?"\n'
                    "cursor.execute(query, (user_id,))\n"
                ),
                "description": (
                    "Replaces unsafe SQL concatenation with "
                    "a parameterized query."
                ),
            }

        else:
            raise AssertionError(
                "Unexpected structured-output schema."
            )

        return LLMResponse(
            content=json.dumps(response),
            model="test-model",
            tokens=25,
        )


def make_finding() -> Finding:
    return Finding(
        finding_id="test-finding-1",
        cwe_id="CWE-89",
        severity=Severity.HIGH,
        confidence=0.9,
        message="Potential SQL injection",
        explanation="User input is concatenated into SQL.",
        file_path="example.py",
        line_number=2,
        evidence=(
            'query = "SELECT * FROM users WHERE id = " + user_id'
        ),
        source="test",
        suggested_remediation=(
            "Use parameterized SQL queries."
        ),
    )


SOURCE_CODE = (
    'user_id = input("User ID: ")\n'
    'query = "SELECT * FROM users WHERE id = " + user_id\n'
    "cursor.execute(query)\n"
)


def test_refactor_generates_structured_patch():
    provider = FakeProvider()

    patch = generate_patch(
        provider=provider,
        finding=make_finding(),
        source_code=SOURCE_CODE,
    )

    assert provider.call_count == 1
    assert isinstance(patch, Patch)
    assert patch.finding_id == "test-finding-1"

    # The diff is now generated locally from the original and
    # revised source, rather than being generated by the LLM.
    assert patch.unified_diff.startswith("--- example.py\n")
    assert "+++ example.py\n" in patch.unified_diff

    # Confirm that the unsafe SQL is removed and parameterized
    # SQL is added.
    assert (
        '-query = "SELECT * FROM users WHERE id = " + user_id'
        in patch.unified_diff
    )
    assert (
        '+query = "SELECT * FROM users WHERE id = ?"'
        in patch.unified_diff
    )
    assert (
        "+cursor.execute(query, (user_id,))"
        in patch.unified_diff
    )

    assert patch.description


def test_critic_approves_valid_patch():
    provider = FakeProvider()
    finding = make_finding()

    patch = Patch(
        finding_id=finding.finding_id,
        unified_diff=(
            "--- example.py\n"
            "+++ example.py\n"
            "@@ -1 +1 @@\n"
            "-unsafe_query\n"
            "+safe_query\n"
        ),
        description="Replace unsafe SQL with a parameterized query.",
    )

    result = review_patch(
        provider=provider,
        finding=finding,
        patch=patch,
        source_code=SOURCE_CODE,
    )

    assert provider.call_count == 1
    assert result.approved is True
    assert result.confidence == 0.95
    assert result.issues == []


def test_critic_rejects_patch_for_different_finding():
    provider = FakeProvider()
    finding = make_finding()

    wrong_patch = Patch(
        finding_id="different-finding",
        unified_diff="some diff",
        description="Unrelated patch",
    )

    with pytest.raises(ValueError, match="finding_id"):
        review_patch(
            provider=provider,
            finding=finding,
            patch=wrong_patch,
            source_code=SOURCE_CODE,
        )

    assert provider.call_count == 0


def test_critic_rejects_empty_patch():
    provider = FakeProvider()
    finding = make_finding()

    empty_patch = Patch(
        finding_id=finding.finding_id,
        unified_diff=None,
        description="No patch generated.",
    )

    with pytest.raises(ValueError, match="empty unified diff"):
        review_patch(
            provider=provider,
            finding=finding,
            patch=empty_patch,
            source_code=SOURCE_CODE,
        )

    assert provider.call_count == 0